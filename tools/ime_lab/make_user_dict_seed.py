"""Generate the reproducible preset user-dictionary snapshot for the host T9 speed gate.

The snapshot is a Rime userdb backup (*.userdb.txt) for the `rime_ice` user
dictionary used by the t9_pinyin script translator. Entries are sampled only from
the project's own dictionaries (rime_ice cn_dicts 8105 and base), never from any
evaluation text, fixture or replay result. Learning history is simulated with
librime's own decay rule (dee = sum of increments * exp((t_i - t_last) / 200)):

* single characters and 5-7 character phrases are whole commits (c >= 1);
* 2-4 character words are either commits or sentence components (c = 0, each
  update adds 0.1, as ScriptTranslator::Memorize does for the elements);
* commit counts are Pareto-tailed, last-use age ~ Exp(mean 4000 ticks),
  earlier uses are spaced by ~Exp(mean 600 ticks), present tick 30000.

Sampling probability is proportional to the dictionary weight (frequency), so
common words dominate (2-character median: about the 4,600th most frequent word)
with a natural tail. Same inputs and seed give identical bytes.

  python tools/ime_lab/make_user_dict_seed.py --output tools/ime_lab/fixtures/user_dict_seed_20261009.userdb.txt
"""
from __future__ import annotations

import argparse
import hashlib
import math
from pathlib import Path
import random
import re

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
DICTS = REPO / "app/build/generated/chinese-assets/rime_ice/cn_dicts"
PRESENT_TICK = 30000
# Entries per character length: (length range, dictionary, count, commit share).
PLAN = (((1, 1), "8105.dict.yaml", 300, 1.0), ((2, 2), "base.dict.yaml", 1500, 0.6),
        ((3, 3), "base.dict.yaml", 600, 0.6), ((4, 4), "base.dict.yaml", 450, 0.6),
        ((5, 7), "base.dict.yaml", 150, 1.0))
HAN = re.compile(r"[一-鿿]+\Z")
CODE = re.compile(r"[a-z]+( [a-z]+)*\Z")


def read_entries(path):
    """Highest-weight reading for each text in a Rime dict.yaml (text, code, weight)."""
    best = {}
    body = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if not body:
            body = line == "..."
            continue
        if not line or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) < 3 or not HAN.match(fields[0]) or not CODE.match(fields[1]):
            continue
        text, code, weight = fields[0], fields[1], float(fields[2])
        syllables = code.split(" ")
        if len(syllables) != len(text) or weight <= 0:
            continue
        if text not in best or weight > best[text][2]:
            best[text] = (text, code, weight)
    return best


def sample(entries, count, rng):
    """Frequency-proportional sampling without replacement (Efraimidis-Spirakis)."""
    keyed = sorted(((-math.log(1.0 - rng.random()) / weight, text) for text, _, weight in entries),
                   key=lambda item: (item[0], item[1]))
    return [text for _, text in keyed[:count]]


def history(rng, commit):
    """Return (commits, dee, last tick) from simulated uses with librime's decay rule."""
    uses = min(80, int(1.0 / (1.0 - rng.random()) ** 0.7)) if commit else 1 + int(rng.expovariate(1 / 2.0))
    last = max(1, PRESENT_TICK - int(rng.expovariate(1 / 4000.0)))
    ticks = [last]
    for _ in range(uses - 1):
        ticks.append(max(1, ticks[-1] - 1 - int(rng.expovariate(1 / 600.0))))
    increment = 1.0 if commit else 0.1
    dee = sum(increment * math.exp((tick - last) / 200.0) for tick in ticks)
    return (uses if commit else 0), dee, last


def generate(seed):
    rng = random.Random(seed)
    pools, sources, rows = {}, {}, {}
    for (low, high), name, count, commit_share in PLAN:
        if name not in pools:
            path = DICTS / name
            pools[name] = read_entries(path)
            sources[name] = hashlib.sha256(path.read_bytes()).hexdigest()
        candidates = sorted((entry for text, entry in pools[name].items() if low <= len(text) <= high),
                            key=lambda entry: entry[0])
        for text in sample(candidates, count, rng):
            code = pools[name][text][1]
            commits, dee, tick = history(rng, rng.random() < commit_share)
            rows[(code, text)] = f"c={commits} d={dee:.6g} t={tick}"
    return rows, sources


def render(rows, sources, seed):
    lines = ["# Rime user dictionary",
             f"# Generated by tools/ime_lab/make_user_dict_seed.py --seed {seed}; no evaluation text was used.",
             *(f"# source {name} sha256={digest}" for name, digest in sorted(sources.items())),
             "#@/db_name\trime_ice.userdb", "#@/db_type\tuserdb", f"#@/tick\t{PRESENT_TICK}",
             "#@/user_id\tcyime-replay-seed-20261009"]
    # Same order as a librime backup: userdb keys are "code \ttext".
    for (code, text), value in sorted(rows.items(), key=lambda item: item[0][0] + " \t" + item[0][1]):
        lines.append(f"{code}\t{text}\t{value}")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--seed", type=int, default=20261009)
    args = parser.parse_args(argv)
    if args.output.exists():
        raise SystemExit(f"Output already exists: {args.output}")
    rows, sources = generate(args.seed)
    args.output.write_text(render(rows, sources, args.seed), encoding="utf-8", newline="\n")
    print(f"{len(rows)} entries -> {args.output} sha256={hashlib.sha256(args.output.read_bytes()).hexdigest()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
