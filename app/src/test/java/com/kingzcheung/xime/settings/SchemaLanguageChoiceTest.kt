package com.kingzcheung.xime.settings

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder
import java.io.File

/** GitHub #86：声笔这类没写 language 的导入方案，语言由用户选一次；方案自己写了的不受影响。 */
class SchemaLanguageChoiceTest {
    @get:Rule val tempDir = TemporaryFolder()

    private fun schema(id: String, extra: String = ""): SchemaMeta {
        val file = File(tempDir.root, "$id.schema.yaml")
        file.writeText("schema:\n  schema_id: $id\n  name: 声笔小鹤\n$extra")
        return SchemaManager.parseSchemaYaml(file)!!
    }

    @Test fun `an imported schema without language can take the chosen language`() {
        val sbxm = schema("sbxm")
        assertTrue(sbxm.languageAssignable)
        assertEquals(InputLanguage.UNSPECIFIED, sbxm.language)
        val chosen = SchemaLanguageChoice.applyTo(sbxm, InputLanguage.CHINESE)
        assertEquals(InputLanguage.CHINESE, chosen.language)
        assertTrue(chosen.languageChosen)
        assertEquals(InputLanguage.CHINESE, chosen.toSchemaInfo().profile.language)
        // 没选时原样留在未标注语言。
        assertEquals(sbxm, SchemaLanguageChoice.applyTo(sbxm, null))
    }

    @Test fun `declared and built-in languages are never replaced`() {
        val declared = schema("my_kana", "  language: ja\n")
        assertFalse(declared.languageAssignable)
        assertEquals(InputLanguage.JAPANESE, SchemaLanguageChoice.applyTo(declared, InputLanguage.CHINESE).language)
        // 明写「未标注」也算方案自己的声明。
        assertFalse(schema("plain_und", "  language: und\n").languageAssignable)
        // CyIME 认识的方案（雾凇、五笔）本来就有语言。
        assertFalse(schema("rime_ice").languageAssignable)
        assertFalse(schema("wubi86").languageAssignable)
    }

    @Test fun `schemas shipped or generated by CyIME are not offered a language`() {
        // 14 键英文词典依赖、全拼漏键候选这类自带方案同样没写语言，但不是用户导入的。
        val dependency = schema("cyime_k14_english")
        assertTrue(dependency.languageAssignable)
        val resolved = SchemaLanguageChoice.resolve(dependency, appProvided = true) { InputLanguage.CHINESE }
        assertFalse(resolved.languageAssignable)
        assertEquals(InputLanguage.UNSPECIFIED, resolved.language)
        assertFalse(resolved.languageChosen)
        // 用户导入的照常可选。
        val imported = SchemaLanguageChoice.resolve(schema("sbxm"), appProvided = false) { InputLanguage.CHINESE }
        assertTrue(imported.languageAssignable)
        assertEquals(InputLanguage.CHINESE, imported.language)
    }

    @Test fun `only languages typed through a Rime schema are offered`() {
        val choices = SchemaLanguageChoice.choices
        assertTrue(InputLanguage.CHINESE in choices)
        assertFalse(InputLanguage.ENGLISH in choices)
        assertFalse(InputLanguage.UNSPECIFIED in choices)
        assertTrue(choices.none { it.typesLettersDirectly })
        // 存着一个直接打字母的语言（比如旧数据）时不生效。
        assertEquals(InputLanguage.UNSPECIFIED, SchemaLanguageChoice.applyTo(schema("sbyp"), InputLanguage.GERMAN).language)
    }
}
